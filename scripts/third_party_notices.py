#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from what is actually installed.

Run it in the environment an installer is built from: the file lists every distribution ELI Legal
depends on at run time, with the licence each one declares. It is evidence for a licence review,
not the review itself.
"""

from __future__ import annotations

import importlib.metadata as md
import re
import sys
from pathlib import Path

ROOTS = ("eli-legal",)
EXTRAS = {"gui", "server", "all"}


def _needed(requirement: str, extras: set[str]) -> str | None:
    """The distribution a requirement names, if it applies on this platform for these extras."""
    from packaging.requirements import Requirement

    parsed = Requirement(requirement)
    if parsed.marker is not None and not any(
        parsed.marker.evaluate({"extra": extra}) for extra in (extras or {""})
    ):
        return None
    return re.sub(r"[-_.]+", "-", parsed.name).lower()


def runtime_closure() -> list[md.Distribution]:
    """Everything the shipped extras of ELI Legal pull in. Other projects' optional extras
    (their test and documentation tools) are not followed."""
    seen: dict[str, md.Distribution] = {}
    queue = [(name, EXTRAS) for name in ROOTS]
    while queue:
        name, extras = queue.pop()
        if name in seen:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            continue
        seen[name] = dist
        for requirement in dist.requires or []:
            needed = _needed(requirement, extras)
            if needed:
                queue.append((needed, set()))
    return [d for n, d in sorted(seen.items()) if n not in ROOTS]


def licence_of(dist: md.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier", [])
        if c.startswith("License ::")
    ]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "not declared: check the project"


def main() -> int:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "THIRD_PARTY_NOTICES.md")
    rows = [
        (d.metadata["Name"], d.version, licence_of(d), d.metadata.get("Home-page") or "")
        for d in runtime_closure()
    ]
    lines = [
        "# Third-party software",
        "",
        "An installed copy of ELI Legal includes the following software, each under its own licence.",
        "This list is generated by `scripts/third_party_notices.py` from the build environment. It is",
        "evidence for a licence review, not the review. The licence texts are in each project's",
        "distribution; an installer must ship them.",
        "",
        "| Component | Version | Licence it declares |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic, _ in rows],
        "| Python | "
        f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro} | PSF-2.0 |",
        "",
        "## Qt and PySide6",
        "",
        "The desktop application uses Qt through PySide6, distributed under the GNU Lesser General",
        "Public License v3 (LGPL-3.0). ELI Legal does not modify them. They are shipped as separate",
        "library files in the installation folder so that a recipient can replace them with their",
        "own build, as that licence requires; the installer must not prevent this. Source code for Qt",
        "and PySide6 is available from the Qt Project (https://download.qt.io/ and",
        "https://code.qt.io/). Anyone distributing ELI Legal must keep this notice and the licence",
        "texts with it.",
        "",
        "## Models",
        "",
        "ELI Legal ships no language model. A model you run on your own machine comes under its own",
        "licence, which may restrict commercial or professional use. Check it before using it on a",
        "matter.",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(rows)} components)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
